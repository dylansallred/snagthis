// Regenerates brand.js from the app's pixel wordmark so the prototypes recolour with the accent.
// Run from the repository root: node docs/design/prototypes/updates/build-brand.cjs
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '../../../..');
let s = fs.readFileSync(path.join(root, 'apps/desktop/src/assets/snagthis-logo-title.svg'), 'utf8');
s = s.replace(/<title>.*?<\/title>/, '');
let first = true;
s = s.replace(/fill="#fa5d0e"/g, () => { const out = first ? 'style="fill:var(--accent-logo,#fa5d0e)"' : 'class="pb-face"'; first = false; return out; })
  .replace(/fill="#ffb238"/g, 'class="pb-light"').replace(/fill="#bd3f00"/g, 'class="pb-dark"').replace(/fill="#0c0e11"/g, 'class="pb-glyph"');
const g = s.slice(s.indexOf('<g'), s.lastIndexOf('</g>') + 4).replace(/<g[^>]*>/, '<g>');
const logo = s.replace('<svg ', '<svg class="logo" role="img" aria-label="SnagThis" ');
const button = '<svg class="pbtn" viewBox="0 0 16 16" shape-rendering="crispEdges" aria-hidden="true">' + g + '</svg>';
fs.writeFileSync(path.join(__dirname, 'brand.js'), '// Generated by build-brand.cjs from apps/desktop/src/assets/snagthis-logo-title.svg.\nwindow.SNAG_LOGO = ' + JSON.stringify(logo) + ';\nwindow.SNAG_BUTTON = ' + JSON.stringify(button) + ';\n');
